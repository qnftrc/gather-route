"""Adds Wowhead Forever ore spawn points to the ore database, additively.

Input: the JSON written by tools/wowhead_export_ores.js, {"ores": {ore: {"id", "title", "data"}}},
where data is the page's g_mapperData: {zone: [{"coords": [[x, y], ...], "uiMapId": n, "uiMapName": ...}]}.
uiMapId is the map ID GatherMate uses too, so each one is turned into a region name through the zone
table of the herb merge report (docs/DONNEES_GATHERMATE.md).

HerbRoute/Data/OreDataGatherMate.lua is only read. A Wowhead point within --tol percent of a point of
the same ore and region (GatherMate or already accepted) is a duplicate and is dropped; every other point
is written to a separate file that appends it to HerbRoute_OreData when the addon loads.

usage:
  python3 -I tools/merge_wowhead_ores.py wowhead_ores_mapperdata.json [--tol 0.5] [--report docs/DONNEES_WOWHEAD_MINERAIS.md]
"""
import argparse
import collections
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from merge_gathermate import Grid, sandbox_table  # noqa: E402


def zone_table(path):
    zones = {}
    for line in open(path, encoding="utf-8"):
        m = re.match(r"\|\s*(\d+)\s*\|\s*([^|]+?)\s*\|\s*\d+ / \d+\s*\|", line)
        if m:
            zones[int(m.group(1))] = m.group(2)
    return zones


def fmt(v):
    return ("%.1f" % v).rstrip("0").rstrip(".")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("export")
    ap.add_argument("--base", default="HerbRoute/Data/OreDataGatherMate.lua")
    ap.add_argument("--zone-map", default="docs/DONNEES_GATHERMATE.md")
    ap.add_argument("--out", default="HerbRoute/Data/OreDataWowhead.lua")
    ap.add_argument("--tol", type=float, default=0.5)
    ap.add_argument("--report", default=None)
    args = ap.parse_args()

    zones = zone_table(args.zone_map)
    base = sandbox_table(args.base, "HerbRoute_OreData")
    ours = {}
    for region in base.keys():
        ours[region] = {}
        for ore in base[region].keys():
            ours[region][ore] = [(float(p[1]), float(p[2])) for p in base[region][ore].values()]

    data = json.load(open(args.export, encoding="utf-8"))["ores"]
    additions = collections.defaultdict(lambda: collections.defaultdict(list))
    stats = collections.defaultdict(lambda: [0, 0, 0, 0])  # (ore) -> total, duplicates of the base, among themselves, added
    unmapped = collections.Counter()
    for ore, entry in sorted(data.items()):
        if not entry.get("data"):
            print("no data for", ore, "-", entry.get("title"), file=sys.stderr)
            continue
        per_region = collections.defaultdict(list)
        for zone, items in entry["data"].items():
            for item in items:
                region = zones.get(item.get("uiMapId"))
                if region is None:
                    unmapped[(item.get("uiMapId"), item.get("uiMapName"))] += len(item["coords"])
                    continue
                per_region[region].extend((round(float(x), 1), round(float(y), 1)) for x, y in item["coords"])
        for region, pts in sorted(per_region.items()):
            existing = Grid(ours.get(region, {}).get(ore, []), args.tol)
            accepted = Grid([], args.tol)
            for p in sorted(pts):
                stats[ore][0] += 1
                if existing.near(p, args.tol):
                    stats[ore][1] += 1
                elif accepted.near(p, args.tol):
                    stats[ore][2] += 1
                else:
                    accepted.add(p)
                    additions[region][ore].append(p)
                    stats[ore][3] += 1

    lines = [
        "-- Generated by tools/merge_wowhead_ores.py from Wowhead Forever object maps. Do not edit.",
        "-- Additive only: these points are appended to HerbRoute_OreData; Data/OreDataGatherMate.lua is untouched.",
        "-- A point within %.2f%% of an existing point of the same ore and region was treated as a duplicate." % args.tol,
        "local added = {",
    ]
    for region in sorted(additions):
        lines.append('["%s"] = {' % region.replace('"', '\\"'))
        for ore in sorted(additions[region]):
            pts = ",".join("{%s,%s}" % (fmt(x), fmt(y)) for x, y in additions[region][ore])
            lines.append('["%s"]={%s},' % (ore.replace('"', '\\"'), pts))
        lines.append("},")
    lines += [
        "}",
        "HerbRoute_OreData = HerbRoute_OreData or {}",
        "for region, ores in pairs(added) do",
        "    HerbRoute_OreData[region] = HerbRoute_OreData[region] or {}",
        "    for ore, points in pairs(ores) do",
        "        local list = HerbRoute_OreData[region][ore] or {}",
        "        for _, p in ipairs(points) do list[#list + 1] = p end",
        "        HerbRoute_OreData[region][ore] = list",
        "    end",
        "end",
    ]
    open(args.out, "w", encoding="utf-8").write("\n".join(lines) + "\n")

    total = [sum(s[i] for s in stats.values()) for i in range(4)]
    rows = ["| Minerai | Wowhead | Doublons de la base | Fusionnés entre eux | Ajoutés |", "|---|---|---|---|---|"]
    for ore in sorted(stats):
        s = stats[ore]
        rows.append("| %s | %d | %d | %d | %d |" % (ore, s[0], s[1], s[2], s[3]))
    rows.append("| **Total** | %d | %d | %d | %d |" % tuple(total))
    print("\n".join(rows))
    for (uid, name), n in sorted(unmapped.items(), key=lambda kv: str(kv[0])):
        print("zone not mapped: uiMapId %s (%s): %d points left out" % (uid, name, n), file=sys.stderr)
    if args.report:
        extra = ""
        if unmapped:
            extra = "\n\n## Zones non rattachées\n\n" + "\n".join("- uiMapId %s (%s) : %d points écartés" % (u, n, c) for (u, n), c in unmapped.items())
        open(args.report, "w", encoding="utf-8").write(
            "# Minerais Wowhead fusionnés\n\nGénéré par `tools/merge_wowhead_ores.py`. Tolérance de doublon : %.2f %% de la carte.\n\n%s%s\n"
            % (args.tol, "\n".join(rows), extra))


if __name__ == "__main__":
    main()
